//===-- RV64InstPrinter.h - Convert RV64 MCInst to asm syntax -------*- C++ -*--//
//
// This class prints a RV64 MCInst to a .s file.
//
//===----------------------------------------------------------------------===//

#ifndef LLVM_LIB_TARGET_RV64_MCTARGETDESC_RV64INSTPRINTER_H
#define LLVM_LIB_TARGET_RV64_MCTARGETDESC_RV64INSTPRINTER_H

#include "MCTargetDesc/RV64MCTargetDesc.h"
#include "llvm/MC/MCInstPrinter.h"

namespace llvm {
class RV64InstPrinter : public MCInstPrinter {
public:
  RV64InstPrinter(const MCAsmInfo &MAI, const MCInstrInfo &MII,
                 const MCRegisterInfo &MRI)
      : MCInstPrinter(MAI, MII, MRI) {}

  void printInst(const MCInst *MI, uint64_t Address, StringRef Annot,
                 const MCSubtargetInfo &STI, raw_ostream &O) override;
  void printOperand(const MCInst *MI, unsigned OpNo, const MCSubtargetInfo &STI, raw_ostream &O);

  // Autogenerated by tblgen.
  std::pair<const char *, uint64_t>
  getMnemonic(const MCInst &MI) const override;
  void printInstruction(const MCInst *MI, uint64_t Address, const MCSubtargetInfo &STI, raw_ostream &O);
  static const char *getRegisterName(MCRegister Reg, unsigned AltIdx = RV::NoRegAltName);
};
}

#endif
